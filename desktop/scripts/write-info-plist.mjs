#!/usr/bin/env node
// Writes src-tauri/Info.plist for the build about to be made.
//
// Only one key needs generating, and it is the one key that cannot be shared:
// the URL scheme a browser hands a reading over by (USER_STORIES.md US-7.32).
// LaunchServices gives a scheme to one application system-wide, so if every
// build claimed `papol`, a development build could be the one a reader's
// browser reaches. Every other place a build could tread on the installed
// Papol is already kept apart by its identifier; this keeps the last one.
//
// Kept in step with handoff_scheme() in src-tauri/src/lib.rs.
import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const base = resolve(here, '../src-tauri/tauri.conf.json');
const target = resolve(here, '../src-tauri/Info.plist');

const read = (path) => JSON.parse(readFileSync(path, 'utf8'));

export function handoffScheme(identifier) {
  const suffix = identifier.startsWith('com.mc-pony.papol')
    ? identifier.slice('com.mc-pony.papol'.length)
    : '';
  return `papol${suffix.replaceAll('.', '-')}`;
}

export function infoPlist(identifier) {
  const scheme = handoffScheme(identifier);
  return `<?xml version="1.0" encoding="UTF-8"?>
<!DOCTYPE plist PUBLIC "-//Apple//DTD PLIST 1.0//EN" "http://www.apple.com/DTDs/PropertyList-1.0.dtd">
<!--
  GENERATED by scripts/write-info-plist.mjs for ${identifier}. Do not edit:
  every build regenerates it, because the scheme below belongs to the build
  and not to the repository.

  Merged into the bundle's generated Info.plist by tauri-bundler. Only keys
  Tauri does not derive from tauri.conf.json belong here.

  Registering the scheme is what lets a browser hand a reading over to the
  application (USER_STORIES.md US-7.32). The application answers it in
  handle_run_event, which turns the address back into the bundled page that
  serves the document.

  A scheme is claimed by whichever copy of an application the system decides
  on, so \`role\` is Viewer rather than Editor: Papol shows the document the
  address names and nothing about the address is a claim on the document.
-->
<plist version="1.0">
  <dict>
    <key>CFBundleURLTypes</key>
    <array>
      <dict>
        <key>CFBundleURLName</key>
        <string>${identifier}.handoff</string>
        <key>CFBundleTypeRole</key>
        <string>Viewer</string>
        <key>CFBundleURLSchemes</key>
        <array>
          <string>${scheme}</string>
        </array>
      </dict>
    </array>
  </dict>
</plist>
`;
}

// `tauri --config` merges its argument over tauri.conf.json, so the identifier
// is read the same way: the override's if it names one, the base's otherwise.
export function identifierFor(overridePath) {
  const identifier = overridePath ? read(resolve(overridePath)).identifier : null;
  return identifier || read(base).identifier;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const identifier = identifierFor(process.argv[2]);
  writeFileSync(target, infoPlist(identifier));
  process.stdout.write(`Info.plist: ${identifier} answers ${handoffScheme(identifier)}://\n`);
}
